import type { QuizItem } from "./quiz";

export type BankQuiz = { id: string; topic: string; name: string; sub: string; items: QuizItem[]; art?: string };

// shorthand: tiles (prompt, right, wrong...) and typed (prompt, right, ...also accepted)
const t = (id: string, prompt: string, answer: string, ...options: string[]): QuizItem => ({ id, type: "choose", prompt, answer, options });
const w = (id: string, prompt: string, answer: string, ...alts: string[]): QuizItem => ({ id, type: "type", prompt, answer, alts });
// an order item: the sentence in the right order; the player scrambles it
const o = (id: string, prompt: string, answer: string, why: string): QuizItem => ({ id, type: "order", prompt, answer, words: answer.split(" "), why, art: "order" });

